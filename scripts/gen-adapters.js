function dirStat(abs) {
  const entries = fs.readdirSync(abs, { withFileTypes: true });
  let files = 0;
  let bytes = 0;
  for (const e of entries) {
    const p = path.join(abs, e.name);
    if (e.isDirectory()) {
      const sub = dirStat(p);
      files += sub.files;
      bytes += sub.bytes;
    } else {
      files += 1;
      bytes += fs.statSync(p).size;
    }
  }
  return { files, bytes };
}

function buildReport() {
  const now = new Date();
  const jsonPath = path.join(DIST, 'json', 'tokens.json');
  let tokenCount = 0;
  if (fs.existsSync(jsonPath)) {
    try {
      tokenCount = JSON.parse(fs.readFileSync(jsonPath, 'utf8')).count || 0;
    } catch (e) {
      tokenCount = 0;
    }
  }
  const dirs = fs
    .readdirSync(DIST, { withFileTypes: true })
    .filter((e) => e.isDirectory())
    .map((e) => e.name)
    .sort();
  const rows = [];
  let totalFiles = 0;
  let totalKB = 0;
  for (const d of dirs) {
    const { files, bytes } = dirStat(path.join(DIST, d));
    totalFiles += files;
    totalKB += bytes / 1024;
    rows.push(`| \`${d}/\` | ${files} | ${(bytes / 1024).toFixed(1)} |`);
  }
  const report =
    `# 构建报告 BUILD-REPORT\n\n` +
    `- 生成时间：${now.toISOString()}（${now.toLocaleString()}）\n` +
    `- 令牌数量：${tokenCount}（读自 \`dist/json/tokens.json\` 的 \`count\`）\n` +
    `- dist 目录数：${dirs.length}，文件数：${totalFiles}，总大小：${totalKB.toFixed(1)} KB\n\n` +
    `| 目录 | 文件数 | KB |\n|---|---|---|\n` +
    rows.join('\n') + '\n' +
    `| **合计** | **${totalFiles}** | **${totalKB.toFixed(1)}** |\n\n` +
    `----\n\n*本报告由 scripts/gen-adapters.js 生成；一键编排见 scripts/build-all.js（build-tokens.js → gen-*.js → gen-adapters.js）。*\n`;
  write('BUILD-REPORT.md', report);
  return { dirs: dirs.length, files: totalFiles, kb: totalKB.toFixed(1), count: tokenCount };
}

