const VANILLA_JS = license('//') + `export const THEME_CLASS = 'gl-dark';

/** 直接切换根元素的 gl-dark class。 */
export function applyTheme(isDark) {
  if (typeof document === 'undefined') return;
  document.documentElement.classList.toggle(THEME_CLASS, Boolean(isDark));
}

export function isDarkTheme() {
  return typeof document !== 'undefined' && document.documentElement.classList.contains(THEME_CLASS);
}

/**
 * 初始化主题：读取 localStorage（prefix 为键名，默认 'pajamas-theme'），
 * 并跟随系统 prefers-color-scheme；返回控制句柄。
 */
export function initTheme(prefix) {
  const key = prefix || 'pajamas-theme';
  let media = null;
  if (typeof window !== 'undefined' && window.matchMedia) {
    media = window.matchMedia('(prefers-color-scheme: dark)');
  }
  const stored = typeof localStorage !== 'undefined' ? localStorage.getItem(key) : null;
  const initial = stored != null ? stored === 'dark' : isDarkTheme();
  applyTheme(initial);
  const onMedia = (e) => {
    if (localStorage.getItem(key) == null) applyTheme(e.matches);
  };
  if (media && media.addEventListener) media.addEventListener('change', onMedia);
  return {
    applyTheme,
    applyDark: (v) => applyTheme(v),
    isDark: isDarkTheme,
    setStored: (v) => {
      applyTheme(v);
      if (typeof localStorage !== 'undefined') localStorage.setItem(key, v ? 'dark' : 'light');
    },
    dispose: () => {
      if (media && media.removeEventListener) media.removeEventListener('change', onMedia);
    },
  };
}
`;

